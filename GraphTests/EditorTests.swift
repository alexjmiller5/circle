private let creation = CircleCreationBinding(policy: .init(id: "hangouts-v1", revision: String(repeating: "a", count: 64)),
                                             namespace: "02b8252a-d54d-4049-a1ad-9806953c2cb6", sourceKind: "circle_hangout")

private func editorBindings(log: CircleCreationBinding? = creation, editable: Bool = true) -> CirclePeopleBindings {
    var people = ["id": "id", "name": "label", "circles": "groups", "deleted": "deleted_at", "hangoutCadence": "every"]
    if editable { people["updated"] = "updated_at"; people["hub"] = "hub_at" }
    return CirclePeopleBindings(
        people: .init(table: "contacts", fields: people),
        relations: .init(table: "links", fields: ["id": "id", "person": "subject", "related": "object", "kind": "kind", "deleted": "deleted_at"]),
        locations: .init(table: "bases", fields: ["id": "id", "person": "person", "city": "city", "country": "country", "start": "start", "end": "end", "deleted": "deleted_at"]),
        summaries: summaryTable, imports: importTable, hangouts: hangoutTable, hangoutLog: log)
}

