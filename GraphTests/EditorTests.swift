@Test func editorBindingsDeriveExactlyThePatchAndCreateGrants() throws {
    let bindings = editorBindings()
    try bindings.validate()
    #expect(bindings.scopes.contains("tables:patch:contacts:every"))
    #expect(bindings.scopes.contains("tables:read:contacts:updated_at") && bindings.scopes.contains("tables:read:contacts:hub_at"))
    #expect(bindings.scopes.contains("rows:create:hangouts-v1:" + String(repeating: "a", count: 64)))
    // Cadence without a revision is read-only; logging needs the hangouts it adds to.
    #expect(!editorBindings(log: nil, editable: false).scopes.contains { $0.hasPrefix("tables:patch:") })
    var noReads = editorBindings(); noReads.hangouts = nil
    #expect(throws: (any Error).self) { try noReads.validate() }
    let bad = CircleCreationBinding(policy: .init(id: "Bad Id", revision: "x"), namespace: "nope", sourceKind: "")
    #expect(throws: (any Error).self) { try editorBindings(log: bad).validate() }
    var half = editorBindings(); half = CirclePeopleBindings(
        people: .init(table: "contacts", fields: ["id": "id", "name": "label", "circles": "groups", "deleted": "deleted_at", "updated": "updated_at"]),
        relations: half.relations, locations: half.locations)
    #expect(throws: (any Error).self) { try half.validate() }
}

@Test func peopleCarryTheirCadenceAndRowRevision() throws {
    let bindings = editorBindings()
    let people = Data(#"[{"id":"p1","label":"Person 1","groups":null,"every":"monthly","updated_at":"2026-10-01T00:00:00.000Z","hub_at":"2026-10-01T00:00:01.000Z","deleted_at":null},{"id":"p2","label":"Person 2","groups":null,"every":null,"updated_at":"2026-10-01T00:00:00.000Z","hub_at":null,"deleted_at":null}]"#.utf8)
    let graph = try bindings.graph(people: people, relations: Data("[]".utf8), locations: Data("[]".utf8), selfID: nil)
    #expect(graph.byID["p1"]?.hangoutCadence == "monthly")
    #expect(graph.byID["p1"]?.revision == GraphRowRevision(updatedAt: "2026-10-01T00:00:00.000Z", hubAt: "2026-10-01T00:00:01.000Z"))
    #expect(graph.byID["p2"]?.hangoutCadence == nil)
    // A row the hub has not stamped yet has no revision to patch against.
    #expect(graph.byID["p2"]?.revision == nil)
}

private actor Recorder: CircleHTTPClient {
    var raw: [(path: String, body: Data)] = []
    let replies: [(Int, String)]
    init(_ replies: [(Int, String)]) { self.replies = replies }
    func request(path: String, method: String, body: Data?, maxBytes: Int) async throws -> CircleHTTPReply {
        raw.append((path, body ?? Data("{}".utf8)))
        let bodies = raw
        let (status, text) = replies[min(bodies.count - 1, replies.count - 1)]
        return CircleHTTPReply(status: status, data: Data(text.utf8))
    }
}

@Test func cadenceEditsAreRevisionCheckedPatches() async throws {
    let recorder = Recorder([(200, #"{"id":"p1","revision":{"updated_at":"2026-10-13T00:00:00.000Z","hub_at":"2026-10-13T00:00:00.500Z"}}"#),
                             (409, #"{"error":"stale"}"#)])
    let editor = try #require(CircleEditor(client: recorder, bindings: editorBindings()))
    let revision = GraphRowRevision(updatedAt: "2026-10-01T00:00:00.000Z", hubAt: "2026-10-01T00:00:01.000Z")
    let next = try await editor.setHangoutCadence("weekly", personID: "p1", revision: revision)
    #expect(next == GraphRowRevision(updatedAt: "2026-10-13T00:00:00.000Z", hubAt: "2026-10-13T00:00:00.500Z"))
    let first = await recorder.raw[0]
    let sent = (path: first.path, body: try JSONSerialization.jsonObject(with: first.body) as! [String: Any])
    #expect(sent.path == "/v1/rows/patch")
    #expect(sent.body["table"] as? String == "contacts" && sent.body["id"] as? String == "p1")
    #expect(sent.body["values"] as? [String: String] == ["every": "weekly"])
    #expect(sent.body["expected_revision"] as? [String: String] == ["updated_at": revision.updatedAt, "hub_at": revision.hubAt])
    await #expect(throws: CircleEditorError.changedElsewhere) { _ = try await editor.setHangoutCadence(nil, personID: "p1", revision: revision) }
    // Read-only bindings offer no editor.
    #expect(CircleEditor(client: recorder, bindings: editorBindings(log: nil, editable: false)) == nil)
}

@Test func loggedHangoutsAreCreateOnlyRowsWithAHubComputedIdentity() async throws {
    let recorder = Recorder([(200, #"{"kind":"created","policy":{"id":"hangouts-v1","revision":"\#(String(repeating: "a", count: 64))"},"id":"3835d77d86e1518cb0adce04d4dbd82d","revision":{"updated_at":"2026-10-14T01:02:03.250Z","hub_at":"2026-10-13T01:02:03.500Z"},"originId":"manual:x:y"}"#),
                             (200, #"{"kind":"existing","policy":{"id":"hangouts-v1","revision":"\#(String(repeating: "a", count: 64))"},"id":"3835d77d86e1518cb0adce04d4dbd82d"}"#),
                             (422, #"{"error":"creation_rejected"}"#)])
    let editor = try #require(CircleEditor(client: recorder, bindings: editorBindings()))
    let source = UUID(uuidString: "0F8FAD5B-D9CB-469F-A165-70867728950E")!
    let now = Date(timeIntervalSince1970: 1_791_939_723.25)
    #expect(try await editor.logHangout(day: "2026-10-12", people: ["p1", "p2"], sourceID: source, now: now) == "3835d77d86e1518cb0adce04d4dbd82d")
    let first = await recorder.raw[0]
    let sent = (path: first.path, body: try JSONSerialization.jsonObject(with: first.body) as! [String: Any])
    #expect(sent.path == "/v1/rows/create")
    #expect(Set(sent.body.keys) == ["policy", "sourceId", "occurrenceKey", "target", "updatedAt", "values"])
    #expect(sent.body["sourceId"] as? String == "0f8fad5b-d9cb-469f-a165-70867728950e" && sent.body["occurrenceKey"] as? Int == 0)
    #expect(sent.body["target"] as? [String: String] == ["kind": "generated", "id": "3835d77d86e1518cb0adce04d4dbd82d"])
    #expect(sent.body["updatedAt"] as? String == "2026-10-14T01:02:03.250Z")
    let values = try #require(sent.body["values"] as? [String: Any])
    #expect(values["day"] as? String == "2026-10-12" && values["who"] as? String == #"["p1","p2"]"#)
    // A retry after a lost reply settles as existing; a refusal is an error, never a success.
    #expect(try await editor.logHangout(day: "2026-10-12", people: ["p1", "p2"], sourceID: source, now: now) == "3835d77d86e1518cb0adce04d4dbd82d")
    await #expect(throws: CircleEditorError.self) { _ = try await editor.logHangout(day: "2026-10-12", people: ["p1"], sourceID: source, now: now) }
}
